import type { AutoEntry, SaveReceipt } from './autosave';
import type { ImportDraft, Duplicate, ImportChoice } from './transfer';
import type { ChordPage } from './chords';
import type { BibleMeta,BibleMapping,BiblePreview,SqlSelection,Verse,Passage } from './bible';
import type { Theme, Catalog, Content, ContentKind } from './content';
import type { Song } from './songs';
import type { EntityKind, LibraryRecord } from './models';
export type Monitor = { id: number; label: string; primary: boolean; availableForProjection: boolean };
export type Snapshot = { revision: number; text: string; chords?:ChordPage; theme: Theme; black: boolean; hidden: boolean; outputOpen: boolean; status: string; mode: 'closed' | 'rehearsal' | 'external' };
export type InterfaceTheme = 'dark' | 'light';
export type Initial = { interfaceTheme: InterfaceTheme; draft: string; dataPath: string; monitors: Monitor[]; snapshot: Snapshot };
export interface Bridge {
  selectImport():Promise<ImportDraft|null>;
  previewImport(draft:ImportDraft):Promise<Duplicate[]>;
  confirmImport(draft:ImportDraft,choice:ImportChoice,target:Duplicate|null):Promise<{kind:'song'|'text';value:Song|import('./content').TextContent}|null>;
  recovery():Promise<{epoch:string;receipt:SaveReceipt|null}>;
  autosave(epoch:string,entries:AutoEntry[]):Promise<SaveReceipt>;
  initial(): Promise<Initial>;
  setInterfaceTheme(theme: InterfaceTheme): Promise<void>;
  save(text: string): Promise<void>;
  present(text: string | { text:string; theme:Theme; chords?:ChordPage }): Promise<void>;
  openOutput(id: number | null): Promise<boolean>;
  closeOutput(): Promise<void>;
  black(): Promise<void>;
  hideText(): Promise<void>;
  listSongs(): Promise<{ songs: Song[]; skipped: number }>;
  saveSong(song: Song): Promise<Song>;
  bibleCatalog():Promise<{versions:BibleMeta[];defaultId:string|null;skipped:number}>;
  selectBibleSql():Promise<SqlSelection|null>;
  previewBible(token:string,mapping:BibleMapping):Promise<BiblePreview>;
  cancelBibleImport():Promise<void>;
  importBible(token:string,fields:Record<string,unknown>,mode:'new'|'copy'|'replace',replaceId:string|null,confirmed:boolean):Promise<BibleMeta|null>;
  defaultBible(id:string):Promise<void>;
  removeBible(id:string):Promise<boolean>;
  queryBible(id:string,request:{reference?:string;search?:string;book?:number;chapter?:number}):Promise<{verses:Verse[];truncated:boolean;books:number[];chapters:number[]}>;
  biblePassage(id:string,reference:string):Promise<Passage>;
  catalog(): Promise<Catalog>;
  saveContent(kind:ContentKind, value:Content): Promise<Content>;
  selectProgram(id:string): Promise<void>;
  importImage(): Promise<string|null>;
  listRecords(kind: EntityKind): Promise<LibraryRecord[]>;
  saveRecord(record: LibraryRecord): Promise<LibraryRecord>;
  createBackup(): Promise<string | null>;
  restoreBackup(): Promise<{ draft: string; previousBackup: string } | null>;
  onState(callback: (snapshot: Snapshot) => void): () => void;
}
